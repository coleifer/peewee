class Operation(object):
    """Encapsulate a single schema altering operation."""
    def __init__(self, migrator, fn, *args, **kwargs):
        self.migrator = migrator
        self.fn = fn
        self.args = args
        self.kwargs = kwargs

    def execute(self, node):
        self.migrator.database.execute(node)

    def _handle_result(self, result):
        if isinstance(result, (Node, Context)):
            self.execute(result)
        elif isinstance(result, Operation):
            result.run()
        elif isinstance(result, (list, tuple)):
            for item in result:
                self._handle_result(item)

    def run(self):
        self._handle_result(self.fn(self.migrator, *self.args, **self.kwargs))


def operation(fn):
    @functools.wraps(fn)
    def inner(self, *args, **kwargs):
        return Operation(self, fn, *args, **kwargs)
    return inner


def _check_table_name(name):
    if '.' in name:
        raise ValueError('Table name "%s" is schema-qualified. Use the '
                         'migrator schema= parameter instead.' % name)
    return name


def make_index_name(table_name, columns):
    return _truncate_constraint_name('_'.join((table_name,) + tuple(columns)))


class SchemaMigrator(object):
    explicit_create_foreign_key = False
    explicit_delete_foreign_key = False
    supports_schema = True
    transactional_ddl = True

    def __init__(self, database, schema=None):
        if schema is not None and not self.supports_schema:
            raise ValueError('%s does not support schema=.'
                             % type(self).__name__)
        self.database = database
        self.schema = schema

    def _table(self, table, schema=None):
        return Entity(schema or self.schema, _check_table_name(table))

    def migrate(self, *operations):
        for operation in operations:
            operation.run()

    @contextmanager
    def migration_context(self, atomic=True):
        if atomic and self.transactional_ddl:
            with self.database.atomic():
                yield
        else:
            yield

    def make_context(self):
        return self.database.get_sql_context()

    @classmethod
    def from_database(cls, database, schema=None):
        if isinstance(database, Proxy):
            if database.obj is None:
                raise ValueError('Database proxy is uninitialized.')
            database = database.obj

        if CockroachDatabase and isinstance(database, CockroachDatabase):
            migrator = CockroachDBMigrator
        elif isinstance(database, PostgresqlDatabase):
            migrator = PostgresqlMigrator
        elif isinstance(database, MySQLDatabase):
            migrator = MySQLMigrator
        elif isinstance(database, SqliteDatabase):
            migrator = SqliteMigrator
        else:
            raise ValueError('Unsupported database: %s' % database)
        return migrator(database, schema=schema)

    @operation
    def apply_default(self, table, column_name, field):
        default = field.default
        if callable(default):
            default = default()

        return (self.make_context()
                .literal('UPDATE ')
                .sql(self._table(table))
                .literal(' SET ')
                .sql(Expression(
                    Entity(column_name),
                    OP.EQ,
                    field.db_value(default),
                    flat=True)))

    def _alter_table(self, ctx, table):
        return ctx.literal('ALTER TABLE ').sql(self._table(table))

    def _alter_column(self, ctx, table, column):
        return (self
                ._alter_table(ctx, table)
                .literal(' ALTER COLUMN ')
                .sql(Entity(column)))

    @operation
    def alter_add_column(self, table, column_name, field,
                         allow_not_null=False):
        # Make field null at first.
        ctx = self.make_context()

        # Add as nullable unless explicitly allowed to be NOT NULL.
        field_null = field.null
        if not allow_not_null:
            field.null = True

        # Set the field's column-name and name, if it is not set or doesn't
        # match the new value.
        if field.column_name != column_name:
            field.name = field.column_name = column_name

        (self
         ._alter_table(ctx, table)
         .literal(' ADD COLUMN ')
         .sql(field.ddl(ctx)))

        field.null = field_null
        if isinstance(field, ForeignKeyField):
            self.add_inline_fk_sql(ctx, field)
        return ctx

    @operation
    def add_constraint(self, table, name, constraint):
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' ADD CONSTRAINT ')
                .sql(Entity(name))
                .literal(' ')
                .sql(constraint))

    @operation
    def add_unique(self, table, *column_names):
        constraint_name = 'uniq_%s' % '_'.join(column_names)
        constraint = NodeList((
            SQL('UNIQUE'),
            EnclosedNodeList([Entity(column) for column in column_names])))
        return self.add_constraint(table, constraint_name, constraint)

    @operation
    def drop_constraint(self, table, name):
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' DROP CONSTRAINT ')
                .sql(Entity(name)))

    def add_inline_fk_sql(self, ctx, field):
        meta = field.rel_model._meta
        ctx = (ctx
               .literal(' REFERENCES ')
               .sql(self._table(meta.table_name, meta.schema))
               .literal(' ')
               .sql(EnclosedNodeList((Entity(field.rel_field.column_name),))))
        if field.on_delete is not None:
            ctx = ctx.literal(' ON DELETE %s' % field.on_delete)
        if field.on_update is not None:
            ctx = ctx.literal(' ON UPDATE %s' % field.on_update)
        return ctx

    @operation
    def add_foreign_key_constraint(self, table, column_name, rel, rel_column,
                                   on_delete=None, on_update=None,
                                   constraint_name=None, rel_schema=None):
        constraint = constraint_name or 'fk_%s_%s_refs_%s' % (table,
                                                              column_name,
                                                              rel)
        ctx = (self
               .make_context()
               .literal('ALTER TABLE ')
               .sql(self._table(table))
               .literal(' ADD CONSTRAINT ')
               .sql(Entity(_truncate_constraint_name(constraint)))
               .literal(' FOREIGN KEY ')
               .sql(EnclosedNodeList((Entity(column_name),)))
               .literal(' REFERENCES ')
               .sql(self._table(rel, rel_schema))
               .literal(' (')
               .sql(Entity(rel_column))
               .literal(')'))
        if on_delete is not None:
            ctx = ctx.literal(' ON DELETE %s' % on_delete)
        if on_update is not None:
            ctx = ctx.literal(' ON UPDATE %s' % on_update)
        return ctx

    @operation
    def add_column(self, table, column_name, field, allow_not_null=False):
        field = field.clone()
        # Adding a column is complicated by the fact that if there are rows
        # present and the field is non-null, then we need to first add the
        # column as a nullable field, then set the value, then add a not null
        # constraint.
        if not field.null and field.default is None and not allow_not_null:
            raise ValueError('%s is not null but has no default' % column_name)

        is_foreign_key = isinstance(field, ForeignKeyField)
        if is_foreign_key and not field.rel_field:
            raise ValueError('Foreign keys must specify a `field`.')

        operations = [
            self.alter_add_column(table, column_name, field, allow_not_null)
        ]

        # In the event the field is *not* nullable, update with the default
        # value and set not null.
        if not field.null and not allow_not_null:
            operations.extend([
                self.apply_default(table, column_name, field),
                self.add_not_null(table, column_name)])

        if is_foreign_key and self.explicit_create_foreign_key:
            operations.append(
                self.add_foreign_key_constraint(
                    table,
                    column_name,
                    field.rel_model._meta.table_name,
                    field.rel_field.column_name,
                    field.on_delete,
                    field.on_update,
                    rel_schema=field.rel_model._meta.schema))

        if field.index or field.unique:
            using = getattr(field, 'index_type', None)
            operations.append(self.add_index(table, (column_name,),
                                             field.unique, using))

        return operations

    def get_foreign_key_constraint(self, table, column_name):
        for fk in self.database.get_foreign_keys(table, self.schema):
            if fk.column == column_name and fk.name:
                return fk.name
        raise AttributeError(
            'Unable to find foreign key constraint for '
            '"%s" on table "%s".' % (column_name, table))

    @operation
    def drop_foreign_key_constraint(self, table, column_name):
        raise NotImplementedError

    @operation
    def drop_column(self, table, column_name, cascade=True):
        ctx = self.make_context()
        (self._alter_table(ctx, table)
         .literal(' DROP COLUMN ')
         .sql(Entity(column_name)))

        if cascade:
            ctx.literal(' CASCADE')

        fk_columns = [fk.column for fk in
                      self.database.get_foreign_keys(table, self.schema)]
        if column_name in fk_columns and self.explicit_delete_foreign_key:
            return [self.drop_foreign_key_constraint(table, column_name), ctx]

        return ctx

    @operation
    def rename_column(self, table, old_name, new_name):
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' RENAME COLUMN ')
                .sql(Entity(old_name))
                .literal(' TO ')
                .sql(Entity(new_name)))

    @operation
    def add_not_null(self, table, column):
        return (self
                ._alter_column(self.make_context(), table, column)
                .literal(' SET NOT NULL'))

    @operation
    def drop_not_null(self, table, column):
        return (self
                ._alter_column(self.make_context(), table, column)
                .literal(' DROP NOT NULL'))

    @operation
    def add_column_default(self, table, column, default):
        if default is None:
            raise ValueError('`default` must be not None/NULL.')
        if callable(default):
            default = default()
        # Try to handle SQL functions and string literals, otherwise pass as a
        # bound value.
        if isinstance(default, str) and default.endswith((')', "'")):
            default = SQL(default)

        return (self
                ._alter_table(self.make_context(), table)
                .literal(' ALTER COLUMN ')
                .sql(Entity(column))
                .literal(' SET DEFAULT ')
                .sql(default))

    @operation
    def drop_column_default(self, table, column):
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' ALTER COLUMN ')
                .sql(Entity(column))
                .literal(' DROP DEFAULT'))

    @operation
    def alter_column_type(self, table, column, field, cast=None):
        # ALTER TABLE <table> ALTER COLUMN <column>
        ctx = self.make_context()
        ctx = (self
               ._alter_column(ctx, table, column)
               .literal(' TYPE ')
               .sql(field.ddl_datatype(ctx)))
        if cast is not None:
            if not isinstance(cast, Node):
                cast = SQL(cast)
            ctx = ctx.literal(' USING ').sql(cast)
        return ctx

    @operation
    def rename_table(self, old_name, new_name):
        # The new name must not be qualified, the table stays in-place.
        return (self
                ._alter_table(self.make_context(), old_name)
                .literal(' RENAME TO ')
                .sql(Entity(new_name)))

    @operation
    def drop_table(self, table, safe=False, cascade=False, schema=None):
        ctx = self.make_context().literal(
            'DROP TABLE IF EXISTS ' if safe else 'DROP TABLE ')
        ctx = ctx.sql(self._table(table, schema))
        return ctx.literal(' CASCADE') if cascade else ctx

    @operation
    def add_index(self, table, columns, unique=False, using=None, where=None,
                  nulls_distinct=None, name=None):
        ctx = self.make_context()
        index_name = name or make_index_name(table, columns)
        table_obj = Table(_check_table_name(table), schema=self.schema)
        cols = [getattr(table_obj.c, column) for column in columns]
        index = Index(index_name, table_obj, cols, unique=unique, using=using,
                      where=where, nulls_distinct=nulls_distinct)
        if self.database.index_value_literals:
            # Sqlite prohibits bound parameters in partial-index predicates.
            index = ValueLiterals(index)
        return ctx.sql(index)

    @operation
    def drop_index(self, table, index_name):
        return (self
                .make_context()
                .literal('DROP INDEX ')
                .sql(self._table(index_name)))

    @operation
    def sql(self, sql, params=None):
        return SQL(sql, params)


class PostgresqlMigrator(SchemaMigrator):
    def _primary_key_columns(self, tbl):
        query = """
            SELECT pg_attribute.attname
            FROM pg_index, pg_class, pg_attribute
            WHERE
                pg_class.oid = %s::regclass AND
                indrelid = pg_class.oid AND
                pg_attribute.attrelid = pg_class.oid AND
                pg_attribute.attnum = any(pg_index.indkey) AND
                indisprimary;
        """
        # regclass parses the identifier, so it is passed quoted.
        name, _ = self.make_context().sql(self._table(tbl)).query()
        cursor = self.database.execute_sql(query, (name,))
        return [row[0] for row in cursor.fetchall()]

    @operation
    def set_search_path(self, schema_name):
        return (self
                .make_context()
                .literal('SET search_path TO ')
                .sql(Entity(schema_name)))

    @operation
    def rename_table(self, old_name, new_name):
        pk_names = self._primary_key_columns(old_name)
        ParentClass = super(PostgresqlMigrator, self)

        operations = [
            ParentClass.rename_table(old_name, new_name)]

        if len(pk_names) == 1:
            # Check for existence of primary key sequence.
            seq_name = '%s_%s_seq' % (old_name, pk_names[0])
            query = """
                SELECT 1
                FROM information_schema.sequences
                WHERE LOWER(sequence_name) = LOWER(%s)
                    AND sequence_schema = COALESCE(%s, current_schema())
            """
            cursor = self.database.execute_sql(query, (seq_name, self.schema))
            if bool(cursor.fetchone()):
                new_seq_name = '%s_%s_seq' % (new_name, pk_names[0])
                operations.append(ParentClass.rename_table(
                    seq_name, new_seq_name))

        return operations

    @operation
    def drop_foreign_key_constraint(self, table, column_name):
        fk_constraint = self.get_foreign_key_constraint(table, column_name)
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' DROP CONSTRAINT ')
                .sql(Entity(fk_constraint)))


