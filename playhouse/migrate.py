class MySQLColumn(namedtuple('_Column', ('name', 'definition', 'null', 'pk',
                                         'default', 'extra'))):
    @property
    def is_pk(self):
        return self.pk == 'PRI'

    @property
    def is_unique(self):
        return self.pk == 'UNI'

    @property
    def is_null(self):
        return self.null == 'YES'

    def sql(self, column_name=None, is_null=None):
        if is_null is None:
            is_null = self.is_null
        if column_name is None:
            column_name = self.name
        parts = [
            Entity(column_name),
            SQL(self.definition)]
        if self.is_unique:
            parts.append(SQL('UNIQUE'))
        if is_null:
            parts.append(SQL('NULL'))
        else:
            parts.append(SQL('NOT NULL'))
        if self.is_pk:
            parts.append(SQL('PRIMARY KEY'))
        if self.extra:
            parts.append(SQL(self.extra))
        return NodeList(parts)


class MySQLMigrator(SchemaMigrator):
    explicit_create_foreign_key = True
    explicit_delete_foreign_key = True
    transactional_ddl = False

    def _alter_column(self, ctx, table, column):
        return (self
                ._alter_table(ctx, table)
                .literal(' MODIFY ')
                .sql(Entity(column)))

    @operation
    def rename_table(self, old_name, new_name):
        # An unqualified new name moves the table to the current database.
        return (self
                .make_context()
                .literal('RENAME TABLE ')
                .sql(self._table(old_name))
                .literal(' TO ')
                .sql(self._table(new_name)))

    def _get_column_definition(self, table, column_name):
        name, _ = self.make_context().sql(self._table(table)).query()
        cursor = self.database.execute_sql('DESCRIBE %s;' % name)
        rows = cursor.fetchall()
        for row in rows:
            column = MySQLColumn(*row)
            if column.name == column_name:
                return column
        return False

    @operation
    def drop_foreign_key_constraint(self, table, column_name):
        fk_constraint = self.get_foreign_key_constraint(table, column_name)
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' DROP FOREIGN KEY ')
                .sql(Entity(fk_constraint)))

    def add_inline_fk_sql(self, ctx, field):
        pass

    @operation
    def add_not_null(self, table, column):
        column_def = self._get_column_definition(table, column)
        add_not_null = (self
                        ._alter_table(self.make_context(), table)
                        .literal(' MODIFY ')
                        .sql(column_def.sql(is_null=False)))

        fk_objects = dict(
            (fk.column, fk)
            for fk in self.database.get_foreign_keys(table, self.schema))
        if column not in fk_objects:
            return add_not_null

        fk_metadata = fk_objects[column]
        return (self.drop_foreign_key_constraint(table, column),
                add_not_null,
                self.add_foreign_key_constraint(
                    table,
                    column,
                    fk_metadata.dest_table,
                    fk_metadata.dest_column,
                    fk_metadata.on_delete,
                    fk_metadata.on_update))

    @operation
    def drop_not_null(self, table, column):
        column_def = self._get_column_definition(table, column)
        if column_def.is_pk:
            raise ValueError('Primary keys can not be null')
        return (self
                ._alter_table(self.make_context(), table)
                .literal(' MODIFY ')
                .sql(column_def.sql(is_null=True)))

    @operation
    def rename_column(self, table, old_name, new_name):
        fk_objects = dict(
            (fk.column, fk)
            for fk in self.database.get_foreign_keys(table, self.schema))
        is_foreign_key = old_name in fk_objects

        column = self._get_column_definition(table, old_name)
        rename_ctx = (self
                      ._alter_table(self.make_context(), table)
                      .literal(' CHANGE ')
                      .sql(Entity(old_name))
                      .literal(' ')
                      .sql(column.sql(column_name=new_name)))
        if is_foreign_key:
            fk_metadata = fk_objects[old_name]
            return [
                self.drop_foreign_key_constraint(table, old_name),
                rename_ctx,
                self.add_foreign_key_constraint(
                    table,
                    new_name,
                    fk_metadata.dest_table,
                    fk_metadata.dest_column,
                    fk_metadata.on_delete,
                    fk_metadata.on_update),
            ]
        else:
            return rename_ctx

    @operation
    def alter_column_type(self, table, column, field, cast=None):
        if cast is not None:
            raise ValueError('alter_column_type() does not support cast with '
                             'MySQL.')
        ctx = self.make_context()
        return (self
                ._alter_table(ctx, table)
                .literal(' MODIFY ')
                .sql(Entity(column))
                .literal(' ')
                .sql(field.ddl(ctx)))

    @operation
    def drop_index(self, table, index_name):
        return (self
                .make_context()
                .literal('DROP INDEX ')
                .sql(Entity(index_name))
                .literal(' ON ')
                .sql(self._table(table)))


class SqliteMigrator(SchemaMigrator):
    """
    SQLite supports a subset of ALTER TABLE queries, view the docs for the
    full details http://sqlite.org/lang_altertable.html
    """
    # Table rebuilds rewrite unqualified DDL read out of sqlite_master.
    supports_schema = False
    column_re = re.compile(r'(.+?)\((.+)\)')
    column_split_re = re.compile(r'(?:[^,(]|\([^)]*\))+')
    column_name_re = re.compile(r'''["`']?([\w]+)''')
    fk_re = re.compile(r'FOREIGN KEY\s+\("?([\w]+)"?\)\s+', re.I)

    def __init__(self, *args, **kwargs):
        super(SqliteMigrator, self).__init__(*args, **kwargs)
        self.sqlite_version = self.database.server_version

    @contextmanager
    def migration_context(self, atomic=True):
        # Have to set pragma to avoid cascading deletes, only works outside
        # of a transaction, though.
        fks_enabled = bool(self.database.pragma('foreign_keys'))
        if fks_enabled:
            self.database.pragma('foreign_keys', 0)
        try:
            with super(SqliteMigrator, self).migration_context(atomic):
                yield
        finally:
            if fks_enabled:
                self.database.pragma('foreign_keys', 1)

    def _get_create_table(self, table):
        res = self.database.execute_sql(
            ('select name, sql from sqlite_master '
             'where type=? and LOWER(name)=?'),
            ['table', table.lower()])
        return res.fetchone()

    def _get_triggers(self, table):
        # Triggers, including TEMP triggers, are dropped along with the table
        # during a rebuild, so collect them for re-creation.
        triggers = []
        for master, temp in (('sqlite_master', False),
                             ('sqlite_temp_master', True)):
            res = self.database.execute_sql(
                ('select name, sql from %s '
                 'where type=? and LOWER(tbl_name)=? and sql is not null '
                 'order by rowid') % master,
                ['trigger', table.lower()])
            triggers.extend((name, sql, temp) for name, sql in res.fetchall())
        return triggers

    _trigger_token_re = re.compile(r'''
        (?P<skip>\s+|--[^\n]*|/\*.*?(?:\*/|$))
      | (?P<literal>[xX]?'(?:[^']|'')*')
      | (?P<quoted>"(?:[^"]|"")*"|`(?:[^`]|``)*`|\[[^\]]*\])
      | (?P<word>[\w$]+)
      | (?P<op>.)''', re.S | re.X)

    def _trigger_column_refs(self, sql, table, column):
        """
        Locate references to `table`.`column` in the SQL of a trigger on
        `table`. Returns (own, ambiguous), where `own` is a list of (start,
        end) spans that refer to the column unambiguously (NEW.col, OLD.col,
        table.col, UPDATE OF col) and `ambiguous` counts other references in
        body statements that also mention `table`, which can't be attributed
        to a table without a full SQL parser.
        """
        toks = [(m.lastgroup, m.group(), m.start(), m.end())
                for m in self._trigger_token_re.finditer(sql)
                if m.lastgroup != 'skip']
        names = []
        for kind, text, _, _ in toks:
            if kind == 'quoted':
                q = text[0]
                text = text[1:-1] if q == '[' else \
                    text[1:-1].replace(q * 2, q)
            names.append(text.lower() if kind in ('word', 'quoted') else None)

        def is_op(i, char):
            return 0 <= i < len(toks) and toks[i][:2] == ('op', char)

        col, tbl = column.lower(), table.lower()

        def scope_mentions_table(j):
            # Does the body statement (or WHEN clause) starting at token `j`
            # name the table, bringing its columns into scope?
            while j < len(toks) and not is_op(j, ';') and \
                    not (toks[j][0] == 'word' and names[j] == 'begin'):
                if names[j] == tbl and not (
                        j >= 2 and is_op(j - 1, '.') and
                        names[j - 2] in ('new', 'old')):
                    return True
                j += 1
            return False

        own, ambiguous = [], 0
        in_header, in_update_of, in_when = True, False, False
        mentions_table = False
        for i, (kind, text, start, end) in enumerate(toks):
            word = text.lower() if kind == 'word' else None
            new_scope = False
            if in_header:
                if word == 'begin' and not in_update_of and \
                   not is_op(i - 1, '.'):
                    in_header = in_when = False
                    new_scope = True
                elif word == 'when':
                    in_when = new_scope = True
                elif word == 'of' and i and names[i - 1] == 'update':
                    in_update_of = True
                elif word == 'on':
                    in_update_of = False
            elif is_op(i, ';'):
                new_scope = True
            if new_scope:
                mentions_table = scope_mentions_table(i + 1)
                continue
            if names[i] != col or is_op(i + 1, '.') or is_op(i + 1, '('):
                continue  # Not the column, or a qualifier/table/function.
            if is_op(i - 1, '.') and i >= 2 and \
               names[i - 2] in ('new', 'old', tbl):
                own.append((start, end))
            elif in_update_of:
                own.append((start, end))
            elif (in_when or not in_header) and mentions_table:
                ambiguous += 1
        return own, ambiguous

    def _fix_trigger(self, table, name, sql, temp, column_to_update,
                     new_column):
        # Triggers are dropped along with the original table, so re-create
        # them once the rebuilt table is in place.
        if new_column is None or \
           new_column.lower() != column_to_update.lower():
            own, ambiguous = self._trigger_column_refs(sql, table,
                                                       column_to_update)
            if new_column is None and (own or ambiguous):
                # Re-creating the trigger would fail or leave it pointing at
                # a missing column, so refuse before changing anything.
                raise ValueError(
                    'Cannot drop column "%s": trigger "%s" may reference it. '
                    'Drop the trigger first and re-create it after the '
                    'migration.' % (column_to_update, name))
            if ambiguous:
                raise ValueError(
                    'Cannot rename column "%s": trigger "%s" references it '
                    'in a statement that cannot be rewritten safely. Drop '
                    'the trigger first and re-create it after the '
                    'migration.' % (column_to_update, name))
            if new_column is not None:
                quoted = '"%s"' % new_column.replace('"', '""')
                for start, end in reversed(own):
                    sql = sql[:start] + quoted + sql[end:]
        if temp:
            # sqlite_temp_master stores the SQL without the TEMP keyword.
            sql = re.sub(r'^\s*CREATE\s+', 'CREATE TEMP ', sql, count=1,
                         flags=re.I)
        return sql

    @operation
    def _update_column(self, table, column_to_update, fn):
        columns = set(column.name.lower()
                      for column in self.database.get_columns(table))
        if column_to_update.lower() not in columns:
            raise ValueError('Column "%s" does not exist on "%s"' %
                             (column_to_update, table))

        # Get the SQL used to create the given table.
        table, create_table = self._get_create_table(table)

        # Get the indexes and SQL to re-create indexes.
        indexes = self.database.get_indexes(table)

        # Triggers are dropped with the table and must be re-created.
        triggers = self._get_triggers(table)

        # Make sure the create_table does not contain any newlines or tabs,
        # allowing the regex to work correctly.
        create_table = re.sub(r'\s+', ' ', create_table)

        # Parse out the `CREATE TABLE` and column list portions of the query.
        raw_create, raw_columns = self.column_re.search(create_table).groups()

        # Clean up the individual column definitions.
        split_columns = self.column_split_re.findall(raw_columns)
        column_defs = [col.strip() for col in split_columns]

        new_column_defs = []
        new_column_names = []
        original_column_names = []
        constraint_terms = ('foreign ', 'primary ', 'constraint ', 'check ',
                            'unique ')

        for column_def in column_defs:
            column_name, = self.column_name_re.match(column_def).groups()

            if column_name == column_to_update:
                new_column_def = fn(column_name, column_def)
                if new_column_def:
                    new_column_defs.append(new_column_def)
                    original_column_names.append(column_name)
                    column_name, = self.column_name_re.match(
                        new_column_def).groups()
                    new_column_names.append(column_name)
            else:
                new_column_defs.append(column_def)

                # Avoid treating constraints as columns.
                if not column_def.lower().startswith(constraint_terms):
                    new_column_names.append(column_name)
                    original_column_names.append(column_name)

        # Create a mapping of original columns to new columns.
        original_to_new = dict(zip(original_column_names, new_column_names))
        new_column = original_to_new.get(column_to_update)

        fk_filter_fn = lambda column_def: column_def
        if not new_column:
            # Remove any foreign keys associated with this column.
            fk_filter_fn = lambda column_def: None
        elif new_column != column_to_update:
            # Update any foreign keys for this column.
            fk_filter_fn = lambda column_def: self.fk_re.sub(
                'FOREIGN KEY ("%s") ' % new_column,
                column_def)

        cleaned_columns = []
        for column_def in new_column_defs:
            match = self.fk_re.match(column_def)
            if match is not None and match.groups()[0] == column_to_update:
                column_def = fk_filter_fn(column_def)
            if column_def:
                cleaned_columns.append(column_def)

        # Update the name of the new CREATE TABLE query.
        temp_table = table + '__tmp__'
        rgx = re.compile(r'("?)%s("?)\s*$' % re.escape(table), re.I)
        create = rgx.sub(
            r'\1%s\2' % temp_table,
            raw_create)

        # Create the new table.
        columns = ', '.join(cleaned_columns)
        queries = [
            NodeList([SQL('DROP TABLE IF EXISTS'), Entity(temp_table)]),
            SQL('%s (%s)' % (create.strip(), columns))]

        # Populate new table.
        populate_table = NodeList((
            SQL('INSERT INTO'),
            Entity(temp_table),
            EnclosedNodeList([Entity(col) for col in new_column_names]),
            SQL('SELECT'),
            CommaNodeList([Entity(col) for col in original_column_names]),
            SQL('FROM'),
            Entity(table)))
        drop_original = NodeList([SQL('DROP TABLE'), Entity(table)])

        # Drop existing table and rename temp table.
        queries += [
            populate_table,
            drop_original,
            self.rename_table(temp_table, table)]

        # Re-create user-defined indexes. User-defined indexes will have a
        # non-empty SQL attribute.
        for index in filter(lambda idx: idx.sql, indexes):
            if column_to_update not in index.columns or \
               new_column == column_to_update:
                queries.append(SQL(index.sql))
            elif new_column:
                sql = self._fix_index(index.sql, column_to_update, new_column)
                if sql is not None:
                    queries.append(SQL(sql))

        # Re-create triggers last, so any they touch already exist.
        for name, sql, temp in triggers:
            queries.append(SQL(self._fix_trigger(
                table, name, sql, temp, column_to_update, new_column)))

        return queries

    def _fix_index(self, sql, column_to_update, new_column):
        # Split on the name of the column to update. If it splits into two
        # pieces, then there's no ambiguity and we can simply replace the
        # old with the new.
        parts = sql.split(column_to_update)
        if len(parts) == 2:
            return sql.replace(column_to_update, new_column)

        # Find the list of columns in the index expression.
        lhs, rhs = sql.rsplit('(', 1)

        # Apply the same "split in two" logic to the column list portion of
        # the query.
        if len(rhs.split(column_to_update)) == 2:
            return '%s(%s' % (lhs, rhs.replace(column_to_update, new_column))

        # Strip off the trailing parentheses and go through each column.
        parts = rhs.rsplit(')', 1)[0].split(',')
        columns = [part.strip('"`[]\' ') for part in parts]

        # `columns` looks something like: ['status', 'timestamp" DESC']
        # https://www.sqlite.org/lang_keywords.html
        # Strip out any junk after the column name.
        clean = []
        for column in columns:
            if re.match(r'%s(?:[\'"`\]]?\s|$)' % re.escape(column_to_update),
                        column):
                column = new_column + column[len(column_to_update):]
            clean.append(column)

        return '%s(%s)' % (lhs, ', '.join('"%s"' % c for c in clean))

    @operation
    def drop_column(self, table, column_name, cascade=True, legacy=False):
        if self.sqlite_version >= (3, 35, 0) and not legacy:
            ctx = self.make_context()
            (self._alter_table(ctx, table)
             .literal(' DROP COLUMN ')
             .sql(Entity(column_name)))
            return ctx
        return self._update_column(table, column_name, lambda a, b: None)

    @operation
    def rename_column(self, table, old_name, new_name, legacy=False):
        if self.sqlite_version >= (3, 25, 0) and not legacy:
            return (self
                    ._alter_table(self.make_context(), table)
                    .literal(' RENAME COLUMN ')
                    .sql(Entity(old_name))
                    .literal(' TO ')
                    .sql(Entity(new_name)))
        def _rename(column_name, column_def):
            # Only replace the leading column name identifier to avoid
            # corrupting type names, defaults, or constraints that happen
            # to contain the column name as a substring.
            return re.sub(
                r'(["\'`]?)%s\1' % re.escape(column_name),
                r'\g<1>%s\1' % new_name,
                column_def,
                count=1)
        return self._update_column(table, old_name, _rename)

    @operation
    def add_not_null(self, table, column, legacy=False):
        if self.sqlite_version >= (3, 53, 0) and not legacy:
            return super(SqliteMigrator, self).add_not_null(table, column)

        def _add_not_null(column_name, column_def):
            return column_def + ' NOT NULL'
        return self._update_column(table, column, _add_not_null)

    @operation
    def drop_not_null(self, table, column, legacy=False):
        if self.sqlite_version >= (3, 53, 0) and not legacy:
            return super(SqliteMigrator, self).drop_not_null(table, column)

        def _drop_not_null(column_name, column_def):
            return column_def.replace('NOT NULL', '')
        return self._update_column(table, column, _drop_not_null)

    @operation
    def add_column_default(self, table, column, default):
        if default is None:
            raise ValueError('`default` must be not None/NULL.')
        if callable(default):
            default = default()
        if (isinstance(default, str) and not default.endswith((')', "'"))
            and not default.isdigit()):
            default = "'%s'" % default.replace("'", "''")
        def _add_default(column_name, column_def):
            # Try to handle SQL functions and string literals, otherwise quote.
            return column_def + ' DEFAULT %s' % default
        return self._update_column(table, column, _add_default)

    @operation
    def drop_column_default(self, table, column):
        def _drop_default(column_name, column_def):
            col = re.sub(r'DEFAULT\s+[\w"\'\(\)]+(\s|$)', '', column_def,
                         flags=re.I)
            return col.strip()
        return self._update_column(table, column, _drop_default)

    @operation
    def alter_column_type(self, table, column, field, cast=None):
        if cast is not None:
            raise ValueError('alter_column_type() does not support cast with '
                             'Sqlite.')
        ctx = self.make_context()
        def _alter_column_type(column_name, column_def):
            node_list = field.ddl(ctx)
            sql, _ = ctx.sql(Entity(column)).sql(node_list).query()
            return sql
        return self._update_column(table, column, _alter_column_type)

    @operation
    def add_constraint(self, table, name, constraint):
        if self.sqlite_version >= (3, 53, 0):
            return super(SqliteMigrator, self).add_constraint(
                table, name, constraint)
        raise NotImplementedError

    @operation
    def drop_constraint(self, table, name):
        if self.sqlite_version >= (3, 53, 0):
            return super(SqliteMigrator, self).drop_constraint(table, name)
        raise NotImplementedError

    @operation
    def drop_table(self, table, safe=False, cascade=False, schema=None):
        if cascade:
            # No CASCADE clause in sqlite's DROP TABLE.
            raise NotImplementedError
        return super(SqliteMigrator, self).drop_table(table, safe,
                                                      schema=schema)

    @operation
    def add_unique(self, table, *column_names):
        # 3.53's ADD CONSTRAINT does not extend to UNIQUE constraints.
        raise NotImplementedError

    @operation
    def add_foreign_key_constraint(self, table, column_name, field,
                                   on_delete=None, on_update=None):
        raise NotImplementedError


def migrate(*operations, **kwargs):
    for operation in operations:
        operation.run()
